// Generate Session 1 to Session 5 reading records for all students
export function generateInitialSessions(students: Student[]): ReadingSessionRecord[] {
  const records: ReadingSessionRecord[] = [];
  const sessionMods = [
    { session: 'Session 1', text: READING_TEXTS[0], scoreOffset: -6.2, completion: 80.6, engagement: -0.4, conf: -0.3, anx: +0.8 },
    { session: 'Session 2', text: READING_TEXTS[1], scoreOffset: -4.5, completion: 81.9, engagement: -0.3, conf: -0.2, anx: +0.6 },
    { session: 'Session 3', text: READING_TEXTS[2], scoreOffset: -2.8, completion: 83.2, engagement: -0.2, conf: -0.1, anx: +0.4 },
    { session: 'Session 4', text: READING_TEXTS[3], scoreOffset: -1.2, completion: 84.5, engagement: -0.1, conf: 0.0, anx: +0.2 },
    { session: 'Session 5', text: READING_TEXTS[4], scoreOffset: 0.0, completion: 85.7, engagement: 0.0, conf: 0.0, anx: 0.0 },
  ];

  students.forEach((stu) => {
    sessionMods.forEach((sm, idx) => {
      const readingScore = Math.min(100, Math.max(30, Math.round(stu.readingScore + sm.scoreOffset)));
      const mainIdeaScore = Math.min(100, Math.max(30, Math.round(stu.mainIdea + sm.scoreOffset)));
      const specificInfoScore = Math.min(100, Math.max(30, Math.round(stu.specificInfo + sm.scoreOffset)));
      const inferenceScore = Math.min(100, Math.max(25, Math.round(stu.inference + sm.scoreOffset)));
      const vocabularyScore = Math.min(100, Math.max(25, Math.round(stu.vocabulary + sm.scoreOffset)));
      const engagement = Math.min(5, Math.max(1, +(stu.engagement + sm.engagement).toFixed(1)));
      const confidence = Math.min(5, Math.max(1, +(stu.confidence + sm.conf).toFixed(1)));
      const anxiety = Math.min(5, Math.max(1, +(stu.anxiety + sm.anx).toFixed(1)));
      const motivation = Math.min(5, Math.max(1, +(stu.motivation + sm.conf).toFixed(1)));

      records.push({
        id: `REC-${stu.id}-S${idx + 1}`,
        studentId: stu.id,
        studentName: stu.name,
        class: stu.class,
        session: sm.session,
        readingTextId: sm.text.id,
        readingTextTitle: sm.text.title,
        textType: sm.text.type as any,
        textLevel: sm.text.level as any,
        readingScore,
        mainIdeaScore,
        specificInformationScore: specificInfoScore,
        inferenceScore,
        vocabularyScore,
        taskCompletionPercent: Math.min(100, Math.max(50, Math.round(sm.completion + (readingScore - 75) * 0.3))),
        responseTimeSeconds: Math.round(110 + (100 - readingScore) * 1.5 + (idx * -3)),
        engagement,
        confidence,
        readingAnxiety: anxiety,
        motivation,
        performanceLevel: calculatePerformanceLevel(readingScore),
        date: `2026-09-${10 + idx * 4}`,
      });
    });
  });

  return records;
}

